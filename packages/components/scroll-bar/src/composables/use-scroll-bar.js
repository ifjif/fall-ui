import { useScrollBarEvent } from "./use-scroll-bar-event";
import { useScrollBarState } from "./use-scroll-bar-state";
import { useScrollBarStyle } from "./use-scroll-bar-style";
export function useScrollBar(props, emit) {
  const {
    containerRef,
    innerContentRef,
    existScrollBar,
    showScrollBar,
    thumbHeightRatio,
    thumbHeight,
    trackHeight,
    thumbTopRate,
    scrollTop,
    maxScrollTop,
    thumbTop,
    startY,
    dragging,
    thumbWidth,
    thumbWidthRate,
    trackWidth,
    startX,
    thumbLeft,
    maxScrollLeft,
    scrollLeft,
    thumbLeftRate,
    existHorizontalScrollBar,
    topPosition,
    endPosition,
    leftPosition,
    rightPostion,
    maxThumbTop,
    maxThumbLeft
  } = useScrollBarState()
  const {
    width,
    height,
    maxHeight,
    maxWidth,
    thumbHeightStyle,
    thumbTopStyle,
    thumbWidthStyle,
    thumbLeftStyle,
    thumbRightStyle,
    thumbBottomStyle
  } = useScrollBarStyle(props, thumbHeight, thumbTop, thumbWidth, thumbLeft, scrollLeft, scrollTop)
  const {
    onScroll,
    scrollDown,
    scrollRight,
    onWheel,
    onTouchStart,
    onTouchMove,
    onTouchEnd,
    onDragEnd,
    updateThumbRate,
  } = useScrollBarEvent(
    props,
    emit,
    containerRef,
    existScrollBar,
    existHorizontalScrollBar,
    scrollTop,
    thumbTopRate,
    dragging,
    trackHeight,
    maxScrollTop,
    startY,
    trackWidth,
    startX,
    maxScrollLeft,
    scrollLeft,
    thumbLeftRate,
    topPosition,
    endPosition,
    leftPosition,
    rightPostion,
    maxThumbTop,
    maxThumbLeft
  )

  return {
    containerRef,
    innerContentRef,
    existScrollBar,
    showScrollBar,
    thumbHeightRatio,
    width,
    height,
    maxHeight,
    maxWidth,
    thumbHeightStyle,
    thumbTopStyle,
    thumbWidthStyle,
    thumbWidthRate,
    maxScrollTop,
    maxScrollLeft,
    dragging,
    thumbLeftStyle,
    thumbRightStyle,
    thumbBottomStyle,
    existHorizontalScrollBar,
    topPosition,
    endPosition,
    leftPosition,
    rightPostion,
    onScroll,
    scrollDown,
    scrollRight,
    onWheel,
    onTouchStart,
    onTouchMove,
    onTouchEnd,
    onDragEnd,
    updateThumbRate,
  }
}

